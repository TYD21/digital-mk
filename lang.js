(function () {
  let currentLang = localStorage.getItem('td_lang') || 'en';

  function applyLang(l) {
    currentLang = l;
    localStorage.setItem('td_lang', l);

    // Update all keyed elements
    document.querySelectorAll('[data-key]').forEach(el => {
      const k = el.getAttribute('data-key');
      if (T[l] && T[l][k] !== undefined) el.textContent = T[l][k];
    });

    // Sync toggle buttons
    document.querySelectorAll('.lang-btn').forEach(btn => {
      btn.classList.toggle('active',
        (btn.textContent.trim() === 'EN' && l === 'en') ||
        (btn.textContent.trim() === 'አማ' && l === 'am')
      );
    });

    // Set html lang attribute
    document.documentElement.lang = l === 'am' ? 'am' : 'en';
  }

  // Expose globally so onclick="setLang(...)" works
  window.setLang = applyLang;

  // Apply saved or default language on load
  document.addEventListener('DOMContentLoaded', () => applyLang(currentLang));
})();
